# 评分 vs 未来5日收益 = 5个交易日后的数据才能算
# 例如: 6月3日的评分，需要等到6月10日才能评估（跳过周末）
# 所以月底评估时：6月评分有 ~20个交易日的数据可用
# 最早可评估日期 = 评分日 + 5个交易日

def explain_timing():
    print("时间线示例：")
    print("  6/3 评分 → 6/10 可算IC（需5个交易日实际收益）")
    print("  6/30 月底评估 → 6月有约20个有效IC日")
    print("  样本量：20天 × 20只股票 = 400个数据点")
    print("  统计意义上足够出结论了")


if __name__ == '__main__':
    print(METRICS)
    explain_timing()
