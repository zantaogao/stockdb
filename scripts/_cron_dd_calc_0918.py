cols = ['强买','CMMR','CMMR+','市场']
data = []
for line in rows.strip().split('\n'):
    parts = line.split()
    vals = [None if p=='-' else float(p.replace('+','')) for p in parts[1:]]
    data.append((parts[0], dict(zip(cols, vals))))

def analyze(series):
    nav = 1.0; peak = 1.0; maxdd = 0.0
    for v in series:
        if v is None: continue
        nav *= (1 + v/100)
        peak = max(peak, nav)
        maxdd = min(maxdd, nav/peak - 1)
    return nav-1, maxdd

week_days = ('20260914','20260915','20260916')
for c in cols:
    ser = [d[1][c] for d in data]
    cum, dd = analyze(ser)
    week = [d[1][c] for d in data if d[0] in week_days and d[1][c] is not None]
    wcomp = 1.0
    for v in week: wcomp *= (1+v/100)
    valid = [v for v in ser if v is not None]
    print(f"{c}: 全程累计(复利)={cum*100:+.2f}% 最大回撤={dd*100:.2f}% 日均={sum(valid)/len(valid):+.3f}% N={len(valid)} | 本周(0914-16)复利={(wcomp-1)*100:+.2f}%")

